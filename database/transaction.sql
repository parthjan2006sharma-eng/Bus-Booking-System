
-- Bus Booking System
-- PostgreSQL database setup
-- Run this script against the transaction database.

CREATE TABLE IF NOT EXISTS bus (
                                   bus_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   bus_name VARCHAR(100) NOT NULL,
    source VARCHAR(100) NOT NULL,
    destination VARCHAR(100) NOT NULL,
    travel_date DATE NOT NULL,
    fare NUMERIC NOT NULL,
    total_seats INTEGER NOT NULL
    );

CREATE TABLE IF NOT EXISTS passenger (
                                         passenger_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         name VARCHAR(255) NOT NULL,
    age INTEGER NOT NULL,
    phone VARCHAR(30),
    email VARCHAR(255)
    );

CREATE TABLE IF NOT EXISTS booking (
                                       booking_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       passenger_id INTEGER REFERENCES passenger(passenger_id),
    bus_id INTEGER REFERENCES bus(bus_id),
    seat_number INTEGER NOT NULL,
    booking_date TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    payment_status VARCHAR(50)
    );

